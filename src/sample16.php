<?php

// 単純な代入
// $number に10を代入
$number = 10;

// 複合代入演算子
$number += 5; // $number に5を加える ($number = $number + 5 と同じ)
$number -= 3; // $number から3を引く ($number = $number - 3 と同じ)
$number *= 2; // $number に2を掛ける ($number = $number * 2 と同じ)
$number /= 4; // $number を4で割る ($number = $number / 4 と同じ)
$number %= 3; // $number を3で割った余り ($number = $number % 3 と同じ)

// 結果を出力
echo $number; // 出力: 0

?>
